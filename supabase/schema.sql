-- 11. ROW LEVEL SECURITY
-- ---------------------------------------------------------------------------
alter table members enable row level security;
alter table profiles enable row level security;
alter table monthly_imports enable row level security;
alter table deduction_transactions enable row level security;
alter table balances enable row level security;

-- helper: is the current user an admin?
create or replace function is_admin()
returns boolean language sql stable as $$
  select exists (
    select 1 from profiles where id = auth.uid() and role = 'admin'
  );
$$;

-- profiles: users can read their own profile; admins can read all
drop policy if exists profiles_select on profiles;
create policy profiles_select on profiles for select
  using (id = auth.uid() or is_admin());

drop policy if exists profiles_admin_write on profiles;
create policy profiles_admin_write on profiles for all
  using (is_admin()) with check (is_admin());

-- members: a member can read only their own row; admins read/write all
drop policy if exists members_select_own on members;
create policy members_select_own on members for select
  using (
    is_admin()
    or id = (select member_id from profiles where id = auth.uid())
  );

drop policy if exists members_admin_write on members;
create policy members_admin_write on members for all
  using (is_admin()) with check (is_admin());

-- monthly_imports: admin only (members never need to see raw import batches)
drop policy if exists imports_admin_only on monthly_imports;
create policy imports_admin_only on monthly_imports for all
  using (is_admin()) with check (is_admin());

-- deduction_transactions: member sees only their own; admin sees/writes all
drop policy if exists txn_select_own on deduction_transactions;
create policy txn_select_own on deduction_transactions for select
  using (
    is_admin()
    or member_id = (select member_id from profiles where id = auth.uid())
  );

drop policy if exists txn_admin_write on deduction_transactions;
create policy txn_admin_write on deduction_transactions for all
  using (is_admin()) with check (is_admin());

-- balances: same shape as transactions
drop policy if exists balances_select_own on balances;
create policy balances_select_own on balances for select
  using (
    is_admin()
    or member_id = (select member_id from profiles where id = auth.uid())
  );

drop policy if exists balances_admin_write on balances;
create policy balances_admin_write on balances for all
  using (is_admin()) with check (is_admin());

-- ---------------------------------------------------------------------------
-- 12. MEMBERSHIP REQUESTS
--     A member signs up (creating an auth.users login) and submits one of
--     these with the name/account number they claim. Nothing links their
--     login to a member record until an admin accepts it.
-- ---------------------------------------------------------------------------
create table if not exists membership_requests (
  id               uuid primary key default gen_random_uuid(),
  auth_user_id     uuid not null unique references auth.users(id) on delete cascade,
  name             text not null,
  email            text not null,
  coop_account_no  text not null,
  status           request_status not null default 'pending',
  member_id        uuid references members(id) on delete set null, -- set once accepted
  created_at       timestamptz not null default now(),
  reviewed_at      timestamptz,
  reviewed_by      uuid references auth.users(id)
);

create index if not exists idx_requests_status on membership_requests(status);

alter table membership_requests enable row level security;

-- a signed-in user can see (and re-submit) only their own request; admin sees all
drop policy if exists requests_select_own on membership_requests;
create policy requests_select_own on membership_requests for select
  using (auth_user_id = auth.uid() or is_admin());

drop policy if exists requests_admin_write on membership_requests;
create policy requests_admin_write on membership_requests for all
  using (is_admin()) with check (is_admin());

